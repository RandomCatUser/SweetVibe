_GIRL_COLOR = 5     # magenta (basic 0-7, safe for asciimatics)
_ACCENT_COLOR = 6   # cyan (basic 0-7)


def _scale_to_fit(avail_w, avail_h):
    """Pick the smallest integer zoom (1 = full res) so the canvas fits."""
    fw = len(_FULL[0][0])
    fh = len(_FULL[0])
    zoom = 1
    while True:
        nw = fw // zoom
        nh = fh // zoom
        if nw <= avail_w and nh <= avail_h:
            return zoom
        zoom += 1
        if zoom > fw or zoom > fh:
            return zoom


def _frame_scaled(zoom):
    src = _FULL[_ST["frame"]]
    if zoom <= 1:
        return src
    rows = []
    for i in range(0, len(src), zoom):
        line = "".join(r[j] for r in (src[i],) for j in range(0, len(src[i]), zoom))
        rows.append(line)
    return rows


def _open(player):
    _ST.update(mode="view", frame=0, last=_time.time())
    player.add_log("Nice moves! o/")


def _on_command(cmd, raw_text):
    low = cmd.strip().lower()
    if not (low in (":girl",) or low.startswith(":girl ")):
        return False
    if _player is None:
        return True
    sub = (raw_text.split(None, 1)[1].lower() if len(raw_text.split(None, 1)) > 1
           and raw_text.split(None, 1)[1] else "")
    if sub == "fast":
        _ST["interval"] = 0.05
    elif sub == "slow":
        _ST["interval"] = 0.3
    else:
        _ST["interval"] = 0.1
    _open(_player)
    return True


def _on_key(key_str, action):
    if _ST["mode"] == "none":
        return False
    ks = (key_str or "").lower()
    if ks in ("ctrl+b", "escape", "esc", "\x1b"):
        _ST["mode"] = "none"
        return True
    return True


def _on_tick():
    if _ST["mode"] != "view":
        return
    now = _time.time()
    if now - _ST["last"] >= _ST["interval"]:
        _ST["last"] = now
        _ST["frame"] = (_ST["frame"] + 1) % len(_FULL)


def _draw(screen):
    if _ST["mode"] != "view":
        return
    from asciimatics.screen import Screen as Scr
    try:
        w, h = screen.width, screen.height
        avail_w = max(10, w - 4)
        avail_h = max(6, h - 2)
        zoom = _scale_to_fit(avail_w, avail_h)
        frame = _frame_scaled(zoom)
        fw = len(frame[0])
        fh = len(frame)
        bw = min(fw + 4, w)
        bh = min(fh + 2, h)
        bx = (w - bw) // 2
        by = (h - bh) // 2
        if _player is not None and hasattr(_player, "draw_box"):
            _player.draw_box(bx, by, bw, bh, " DANCE! ", Scr.COLOUR_MAGENTA,
                             rounded=True, bg=Scr.COLOUR_BLACK)
        start_row = 0
        avail_hh = max(0, h - 2)
        if fh > avail_hh:
            start_row = (fh - avail_hh) // 2
        cy = by + 1
        max_w = max(0, bw - 2)
        for line in frame[start_row:start_row + avail_hh]:
            line = line[:max_w]
            try:
                screen.print_at(line.rstrip(), bx + 1, cy, _GIRL_COLOR, Scr.A_BOLD)
            except Exception:
                pass
            cy += 1
        if by + bh - 1 < h:
            try:
                screen.print_at("CTRL+B dismiss".center(bw - 2), bx + 1, by + bh - 1,
                                Scr.COLOUR_BLACK, Scr.A_BOLD, bg=Scr.COLOUR_MAGENTA)
            except Exception:
                pass
    except Exception:
        pass


def setup(player):
    global _player
    _player = player
    player.plugin_hooks["on_command"].append(_on_command)
    player.plugin_hooks["on_draw"].append(_draw)
    player.plugin_hooks["on_key"].append(_on_key)
    player.plugin_hooks["on_tick"].append(_on_tick)
    player.add_log("Girl plugin loaded (:girl)")

